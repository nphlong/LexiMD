import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

const require = createRequire(import.meta.url);
const version = require('mermaid/package.json').version;
const root = process.cwd();
const source = path.join(root, 'node_modules', 'mermaid', 'dist', 'mermaid.min.js');
const assetDir = path.join(root, 'assets', 'preview');
const generatedDir = path.join(root, 'src', 'preview', 'generated');

fs.mkdirSync(assetDir, { recursive: true });
fs.mkdirSync(generatedDir, { recursive: true });
fs.copyFileSync(source, path.join(assetDir, 'mermaid.min.mermaidjs'));
fs.writeFileSync(
  path.join(generatedDir, 'previewVersion.ts'),
  `// Generated by scripts/bundle-preview.mjs. Do not edit.\nexport const PREVIEW_BUNDLE_VERSION = ${JSON.stringify(
    `mermaid@${version}`,
  )};\n`,
);
